import SwiftUI

extension Color {
    /// Creates a color from a `0xRRGGBB` integer, matching the hex literals used by the theme demos.
    init(hex: UInt32) {
        self.init(
            red: Double((hex >> 16) & 0xFF) / 255,
            green: Double((hex >> 8) & 0xFF) / 255,
            blue: Double(hex & 0xFF) / 255
        )
    }
}
